@pytest.mark.parametrize(
    "url",
    [
        "http://files.pythonhosted.org/x",
        "https://evil.example/runtime.whl",
        "https://secret@files.pythonhosted.org/x",
        "https://files.pythonhosted.org/x?token=secret",
    ],
)
def test_rejects_unapproved_wheel_origin_without_echoing_url(tmp_path: Path, url: str) -> None:
    from scripts.prepare_online_payload import PayloadError

    fixture = _fixture(tmp_path)
    text = fixture["lock"].read_text()
    old = f"https://files.pythonhosted.org/packages/fixture/{fixture['wheel'].name}"
    fixture["lock"].write_text(
        text.replace(
            old,
            url.rsplit("/", 1)[0]
            + "/"
            + fixture["wheel"].name
            + ("?token=secret" if "?" in url else ""),
        )
    )
    with pytest.raises(PayloadError, match="URL") as error:
        _prepare(fixture)
    assert "secret" not in str(error.value)


