def test_same_basename_from_unrecorded_source_stays_embedded(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    impostor = tmp_path / "other-application/Qt6Core.dll"
    impostor.parent.mkdir()
    impostor.write_bytes((fixture["dist"] / "_internal/Qt6Core.dll").read_bytes())
    fixture["collect"].write_text(repr(([("Qt6Core.dll", str(impostor), "BINARY")],)))
    payload = _prepare(fixture)
    assert (
        next(e for e in payload["files"] if e["path"].endswith("Qt6Core.dll"))["artifact"] is None
    )


@pytest.mark.parametrize("change", ["content", "extra", "missing", "duplicate"])
def test_rejects_inventory_drift(tmp_path: Path, change: str) -> None:
    from scripts.prepare_online_payload import PayloadError

    fixture = _fixture(tmp_path)
    if change == "content":
        (fixture["dist"] / "_internal/Qt6Core.dll").write_bytes(b"changed after review")
    elif change == "extra":
        (fixture["dist"] / "unexpected.txt").write_text("unexpected")
    elif change == "missing":
        (fixture["dist"] / "InterviewAssistant.exe").unlink()
    else:
        data = json.loads(fixture["inventory"].read_text())
        data["files"].append(dict(data["files"][0], path="interviewassistant.EXE"))
        fixture["inventory"].write_text(json.dumps(data))
    with pytest.raises(PayloadError, match="inventory"):
        _prepare(fixture)


