@pytest.mark.parametrize("unsafe", ["../escape.dll", "vendor/BIN/qt6core.DLL", "symlink"])
def test_rejects_unsafe_unselected_archive_members_before_extraction(
    tmp_path: Path, unsafe: str
) -> None:
    from scripts.prepare_online_payload import PayloadError

    fixture = _fixture(tmp_path)
    payload = _prepare(fixture)
    artifact = next(a for a in payload["artifacts"] if a["kind"] == "wheel")
    with zipfile.ZipFile(fixture["wheel"], "a") as archive:
        if unsafe == "symlink":
            link = zipfile.ZipInfo("vendor/link")
            link.create_system = 3
            link.external_attr = (stat.S_IFLNK | 0o777) << 16
            archive.writestr(link, "../outside")
        else:
            archive.writestr(unsafe, "unselected content")
    digest = _sha(fixture["wheel"].read_bytes())
    fixture["lock"].write_text(
        fixture["lock"]
        .read_text()
        .replace(artifact["sha256"], digest)
        .replace(f"size = {artifact['size']}", f"size = {fixture['wheel'].stat().st_size}")
    )
    shutil.copyfile(fixture["wheel"], fixture["cache"] / f"{digest}.zip")
    with pytest.raises(PayloadError, match="path|member"):
        _prepare(fixture, verify=True)
    assert not (tmp_path / "escape.dll").exists()


