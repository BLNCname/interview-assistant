"""Reconstruct frozen layouts from pinned archive members, without pip/network."""

from __future__ import annotations

import base64
import csv
import hashlib
import io
import json
import shutil
import stat
import zipfile
from pathlib import Path

import pytest


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _fixture(tmp_path: Path, *, hex_record: bool = False) -> dict:
    site = tmp_path / "site-packages"
    dist = tmp_path / "frozen"
    cache = tmp_path / "cache"
    site.mkdir()
    dist.mkdir()
    cache.mkdir()
    info = "fixture_runtime-1.0.dist-info"
    wheel_files = {
        "vendor/bin/Qt6Core.dll": b"selected reviewed runtime DLL",
        f"{info}/METADATA": b"Metadata-Version: 2.1\nName: fixture-runtime\nVersion: 1.0\n",
        f"{info}/WHEEL": b"Wheel-Version: 1.0\nRoot-Is-Purelib: false\nTag: cp312-cp312-win_amd64\n",
    }
    rows = []
    for name, data in wheel_files.items():
        digest = (
            _sha(data)
            if hex_record
            else base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip("=")
        )
        rows.append([name, f"sha256={digest}", len(data)])
    rows.append([f"{info}/RECORD", "", ""])
    record = io.StringIO(newline="")
    csv.writer(record).writerows(rows)
    wheel_files[f"{info}/RECORD"] = record.getvalue().encode()
    wheel = tmp_path / "fixture_runtime-1.0-cp312-cp312-win_amd64.whl"
    with zipfile.ZipFile(wheel, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in wheel_files.items():
            archive.writestr(name, data)
    for name, data in wheel_files.items():
        target = site / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    # These files are generated by the installer; a hashed installed RECORD
    # entry must not make them a candidate for a nonexistent wheel member.
    installer = site / info / "INSTALLER"
    installer.write_bytes(b"uv")
    with (site / info / "RECORD").open("a", newline="", encoding="utf-8") as stream:
        csv.writer(stream).writerow(
            [
                f"{info}/INSTALLER",
                "sha256="
                + base64.urlsafe_b64encode(hashlib.sha256(b"uv").digest()).decode().rstrip("="),
                2,
            ]
        )
    model = b"pinned STT weights fixture"
    frozen_files = {
        "InterviewAssistant.exe": b"private compiled executable",
        "_internal/Qt6Core.dll": wheel_files["vendor/bin/Qt6Core.dll"],
        "_internal/base_library.zip": b"build-specific stdlib",
        "_internal/assets/logo.ico": b"private logo",
        f"_internal/{info}/INSTALLER": b"uv",
        f"_internal/{info}/RECORD": (site / info / "RECORD").read_bytes(),
        "_internal/models/stt/fixture/model.bin": model,
    }
    entries = []
    for name, data in frozen_files.items():
        target = dist / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        entries.append({"path": name, "size": len(data), "sha256": _sha(data)})
    inventory = tmp_path / "inventory.json"
    inventory.write_text(
        json.dumps({"schema_version": 1, "application": "InterviewAssistant", "files": entries})
    )
    collect = tmp_path / "COLLECT-00.toc"
    collect.write_text(
        repr(
            (
                [
                    ("InterviewAssistant.exe", str(dist / "InterviewAssistant.exe"), "EXECUTABLE"),
                    ("Qt6Core.dll", str(site / "vendor/bin/Qt6Core.dll"), "BINARY"),
                    (f"{info}/INSTALLER", str(installer), "DATA"),
                    (f"{info}/RECORD", str(site / info / "RECORD"), "DATA"),
                ],
            )
        )
    )
    archive_hash = _sha(wheel.read_bytes())
    lock = tmp_path / "uv.lock"
    lock.write_text(f"""version = 1
[[package]]
name = "fixture-runtime"
version = "1.0"
source = {{registry = "https://pypi.org/simple"}}
wheels = [{{url = "https://files.pythonhosted.org/packages/fixture/{wheel.name}", hash = "sha256:{archive_hash}", size = {wheel.stat().st_size}}}]
""")
    model_manifest = tmp_path / "model.json"
    model_manifest.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "repository": "official-owner/model",
                "revision": "a" * 40,
                "bundle_subdirectory": "models/stt/fixture",
                "files": [{"path": "model.bin", "size": len(model), "sha256": _sha(model)}],
            }
        )
    )
    shutil.copyfile(wheel, cache / f"{archive_hash}.zip")
    (cache / f"{_sha(model)}.bin").write_bytes(model)
    return {
        "dist": dist,
        "inventory": inventory,
        "collect": collect,
        "lock": lock,
        "site_packages": site,
        "model_manifest": model_manifest,
        "cache": cache,
        "wheel": wheel,
    }


def _prepare(fixture: dict, *, verify: bool = False) -> dict:
    from scripts.prepare_online_payload import prepare_payload

    arguments = {k: v for k, v in fixture.items() if k not in ("cache", "wheel")}
    return prepare_payload(**arguments, verify_cache=fixture["cache"] if verify else None)


def test_exact_partition_preserves_relocated_dll_and_embeds_installer_metadata(
    tmp_path: Path,
) -> None:
    fixture = _fixture(tmp_path)
    payload = _prepare(fixture, verify=True)
    files = {entry["path"]: entry for entry in payload["files"]}
    expected = json.loads(fixture["inventory"].read_text())["files"]
    assert len(files) == len(expected) == len(payload["files"])
    assert all(files[e["path"]]["sha256"] == e["sha256"] for e in expected)
    dll = files["_internal/Qt6Core.dll"]
    assert dll["member"] == "vendor/bin/Qt6Core.dll"
    assert dll["artifact"].startswith("wheel-")
    assert files["InterviewAssistant.exe"]["artifact"] is None
    assert files["_internal/fixture_runtime-1.0.dist-info/INSTALLER"]["artifact"] is None
    assert files["_internal/fixture_runtime-1.0.dist-info/RECORD"]["artifact"] is None
    model = files["_internal/models/stt/fixture/model.bin"]
    assert model["member"] is None and model["artifact"].startswith("model-")
    assert payload["wheel_archives_verified"] is True
    assert payload["artifacts_verified"] is True
    wheel = next(a for a in payload["artifacts"] if a["kind"] == "wheel")
    with zipfile.ZipFile(fixture["wheel"]) as archive:
        assert wheel["expanded_size"] == sum(i.file_size for i in archive.infolist())
    assert next(a for a in payload["artifacts"] if a["kind"] == "file")["expanded_size"] == len(
        b"pinned STT weights fixture"
    )


