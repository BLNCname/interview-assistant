def test_archive_member_must_match_reviewed_frozen_bytes(tmp_path: Path) -> None:
    from scripts.prepare_online_payload import PayloadError

    fixture = _fixture(tmp_path)
    # A fully pinned archive digest is insufficient when the selected member
    # does not match the already reviewed portable file.
    payload = _prepare(fixture)
    artifact = next(a for a in payload["artifacts"] if a["kind"] == "wheel")
    with zipfile.ZipFile(fixture["wheel"], "w") as archive:
        archive.writestr("vendor/bin/Qt6Core.dll", b"different wheel content")
    previous = artifact["sha256"]
    updated = _sha(fixture["wheel"].read_bytes())
    fixture["lock"].write_text(
        fixture["lock"]
        .read_text()
        .replace(previous, updated)
        .replace(f"size = {artifact['size']}", f"size = {fixture['wheel'].stat().st_size}")
    )
    shutil.copyfile(fixture["wheel"], fixture["cache"] / f"{updated}.zip")
    with pytest.raises(PayloadError, match="member"):
        _prepare(fixture, verify=True)


def test_inno_includes_preserve_paths_and_external_indexing(tmp_path: Path) -> None:
    from scripts.prepare_online_payload import write_outputs

    payload = _prepare(_fixture(tmp_path), verify=True)
    output = tmp_path / "output"
    write_outputs(payload, output)
    files = (output / "payload_files.iss").read_text(encoding="utf-8-sig")
    data = (output / "payload_data.iss").read_text(encoding="utf-8-sig")
    assert "[Files]" not in files
    assert 'Source: "{#DistPath}\\InterviewAssistant.exe"' in files
    assert 'Source: "{code:GetPreparedFile|0}"' in files
    assert 'DestDir: "{app}\\_internal"; DestName: "Qt6Core.dll"' in files
    assert "Flags: external ignoreversion" in files
    assert "SetArrayLength(PayloadFiles, 2);" in data
    assert "MemberPath := 'vendor\\bin\\Qt6Core.dll'" in data
    assert "procedure LoadOnlinePayload;" in data
    assert ".ExpandedSize := " in data
    assert "payload_manifest_sha256=" in files and "payload_manifest_sha256=" in data
    assert json.loads((output / "online_payload.json").read_text())["artifacts_verified"] is True


